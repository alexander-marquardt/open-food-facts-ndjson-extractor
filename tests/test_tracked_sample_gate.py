def test_every_derived_value_in_the_sample_is_what_the_code_derives() -> None:
    """Recomputed price, bucket, margin and popularity match the tracked file.

    This is the arm the "Fixed pricing for olive oil" drift needed. The olive oil
    in that sample recorded ``bucket=oils_fats``; the classifier that commit
    shipped returns ``olive_oil`` for it.
    """
    failures = {
        record.get("id"): violations
        for record in _load_sample()
        if (violations := _derived_value_violations(record))
    }
    assert not failures, (
        "the tracked sample disagrees with the code that derives these values. "
        "Regenerate it (README, 'Regenerating it') rather than editing it:\n"
        + json.dumps(failures, indent=2)
    )


def test_the_sample_has_the_shape_a_current_run_emits() -> None:
    failures = {
        record.get("id"): violations
        for record in _load_sample()
        if (violations := _shape_violations(record))
    }
    assert not failures, (
        "the tracked sample's shape is not the shape a current run emits:\n"
        + json.dumps(failures, indent=2)
    )


def test_the_sample_descriptions_agree_with_their_own_attrs() -> None:
    failures = {
        record.get("id"): violations
        for record in _load_sample()
        if (violations := _description_violations(record))
    }
    assert not failures, (
        "a description does not match the attrs it is rendered from, which is what "
        "an in-place edit of the sample looks like:\n" + json.dumps(failures, indent=2)
    )



def test_the_stale_fixture_is_the_file_this_repo_used_to_ship() -> None:
    """Guard the proof below against a fixture that stopped being stale data."""
    fixture = json.loads(STALE_FIXTURE.read_text(encoding="utf-8"))
    assert fixture["commit"] == "e81402b79ed2f3331adcef220308f292a29ed200"
    assert len(fixture["records"]) == 3
    ids = [record["id"] for record in fixture["records"]]
    assert ids == ["0000790200123", "0008112100281", "0008127000019"]


def test_stale_sample_fails_the_derived_value_arm() -> None:
    """The olive-oil drift the issue is named after, caught by re-derivation.

    Two of the three records are rejected on values they *carry*, not on values
    they are missing — so this arm is doing its own work and is not a restatement
    of the shape arm. The third is the control: its pricing was already current in
    January and re-derivation clears it, which is what stops this test from
    passing on a checker that simply rejects everything old.
    """
    by_id = {record["id"]: _derived_value_violations(record) for record in _load_stale()}

    olive_oil = " | ".join(by_id["0008127000019"])
    assert "'oils_fats'" in olive_oil and "'olive_oil'" in olive_oil, olive_oil
    assert "source=serving" in olive_oil, olive_oil

    sesame_oil = " | ".join(by_id["0008112100281"])
    assert "'beverages_soft'" in sesame_oil and "'oils_fats'" in sesame_oil, sesame_oil

    priced_wrong = [
        entry for entry in by_id["0008127000019"] if entry.startswith("price:")
    ]
    assert priced_wrong, "the drifted bucket must move the price too"

    control = by_id["0000790200123"]
    assert not [entry for entry in control if entry.startswith(("price:", "margin:", "attrs['Pricing bucket']", "attrs['Estimated unit price']"))], (
        "the control record's pricing was already current; an arm that rejects it "
        f"is rejecting age, not drift: {control}"
    )


def test_stale_sample_fails_the_shape_arm() -> None:
    """The fields that arrived after January are missing, and the arm names them."""
    for record in _load_stale():
        violations = " | ".join(_shape_violations(record))
        for field in ("category_path", "margin", "popularity"):
            assert f"top-level field {field!r} is absent" in violations, (
                f"{record['id']}: shape arm did not notice {field} was missing: {violations}"
            )


@pytest.mark.parametrize(
    "arm",
    [_derived_value_violations, _shape_violations],
    ids=["derived_values", "shape"],
)
def test_each_arm_clears_the_current_sample_and_rejects_the_stale_one(arm) -> None:
    """Both directions, per arm, in one place: green on current, red on stale."""
    assert not [violation for record in _load_sample() for violation in arm(record)]
    assert all(arm(record) for record in _load_stale())

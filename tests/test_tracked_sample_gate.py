def test_the_readme_records_a_command_the_extractor_still_accepts() -> None:
    """Every flag in the recorded command exists on the extractor's own parser.

    #47 had to reconstruct this command from the shape of the output and from
    ``git log``. Recording it is only half the fix: a recorded command that no
    longer parses sends the next reader back to the archaeology.
    """
    argv = _documented_command()
    assert argv[:4] == ["uv", "run", "-m", "off_demo_extract.extract"], (
        f"the recorded command does not invoke the extractor: {argv[:4]}"
    )

    unused = Path("unused")
    parser = build_parser(unused, unused, unused, unused)
    args = parser.parse_args(argv[4:])

    assert args.output == Path("data/sample-data/clean_products.ndjson"), (
        f"the recorded command writes {args.output}, not the tracked sample"
    )
    assert args.lang == "en"
    assert args.require_category
    assert args.yes, "without --yes the command stops on a prompt when the sample already exists"
    assert args.report.parts[:2] != ("data", "sample-data"), (
        "the recorded command writes its report into the tracked sample directory, "
        "which leaves an untracked file behind after every regeneration"
    )


def test_the_recorded_record_count_is_the_number_of_records_tracked() -> None:
    """``--max-output-records`` and the file agree, so neither can drift alone."""
    args = build_parser(*[Path("unused")] * 4).parse_args(_documented_command()[4:])
    assert args.max_output_records == len(_load_sample())


